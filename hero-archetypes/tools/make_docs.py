"""Regenerate the human-readable docs from the build data.

  script/storyboard.md      ← script/scenes.yaml + build/narration_timing.json
  sources.md (## Images)    ← build/image_credits.json + assets/cutouts (what's actually used)
"""
import json
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).parent))
ROOT = Path(__file__).resolve().parents[1]
import render as R  # noqa: E402  (reuses its time-reference parser)

STYLE = {"stamp": "rubber stamp", "tape": "paper strip", "title": "bold title", "type": "typewriter tag",
         "marker": "marker note", "quote": "quote card"}


def mmss(t):
    return f"{int(t // 60)}:{t % 60:04.1f}"


def describe(e):
    t = e["type"]
    if t == "cutout":
        img = e["img"] if isinstance(e["img"], str) else e["img"][0]
        return f"cutout **{img}** ({e.get('enter', 'pop')})"
    if t == "caption":
        return f"{STYLE.get(e.get('style', 'tape'), e.get('style'))}: “{e['text'].replace(chr(10), ' / ')}”"
    if t == "path":
        return "dotted journey path draws on"
    if t == "montage":
        return "montage: " + "; ".join(f"{(i['img'] if isinstance(i['img'], str) else '+'.join(i['img']))} → “{i['caption'].replace(chr(10), ' ')}”" for i in e["items"])
    if t == "mosaic":
        return "mosaic: every cutout assembles into one giant face"
    if t == "tree":
        return "paper-cut tree (Great Deku Tree)"
    if t == "loop":
        return "cycle diagram: " + " → ".join(e["labels"])
    if t == "darken":
        return "background darkens"
    if t == "divider":
        return "torn-paper divider (split screen)"
    if t == "tint":
        return "Hyrule-green paper panel on one half"
    if t == "credits":
        return "end card with credits"
    return t


def storyboard():
    timing = R.TIMING
    lines = {}
    for s in timing["sections"]:
        for ln in s["lines"]:
            lines[(s["id"], ln["index"])] = ln
    out = ["# Storyboard", "",
           "Generated by `tools/make_docs.py` from `script/scenes.yaml` (edit that file, not this one).",
           f"Runtime: **{mmss(timing['duration'])}** · palettes and fonts in `config.yaml`.", ""]
    scenes = R.SCENES
    starts = [0.0] + [R.T(s.get("start")) for s in scenes[1:]]
    sec_titles = {s["id"]: s["title"] for s in timing["sections"]}
    last_sec = None
    for i, sc in enumerate(scenes):
        t0 = starts[i]
        t1 = starts[i + 1] if i + 1 < len(scenes) else timing["duration"]
        sec = max((s["id"] for s in timing["sections"] if s["start"] <= t0 + 0.6), default=1)
        if sec and sec != last_sec:
            out += [f"## {sec}. {sec_titles[sec]}", ""]
            last_sec = sec
        said = [ln["text"] for (sid, li), ln in lines.items() if t0 - 0.1 <= ln["start"] < t1 - 0.1]
        out += [f"### {sc['id']}  ·  {mmss(t0)}–{mmss(t1)}  ·  palette: {sc.get('palette', 'title')}  ·  in: {sc.get('transition', 'tear') if i else 'open'}", ""]
        if said:
            out += ["> " + " ".join(said), ""]
        for e in sc.get("elements", []):
            at = R.T(e["at"]) if e.get("at") is not None else t0
            out.append(f"- `{mmss(at)}` {describe(e)}")
        out.append("")
    (ROOT / "script" / "storyboard.md").write_text("\n".join(out), encoding="utf-8")


def images_section():
    credits = json.loads((ROOT / "build" / "image_credits.json").read_text())
    used = {p.stem for p in (ROOT / "assets" / "cutouts").glob("*.png")}
    rows = ["## Images", "",
            "Generated by `tools/make_docs.py` from `build/image_credits.json`. Every file is in `assets/public_domain/` (public-domain / open-access) or `assets/stills/` (copyrighted, used under fair use for commentary), and its cut-out version is in `assets/cutouts/`.", "",
            "| Id | Subject | Licence | Source |", "|----|---------|---------|--------|"]
    for kind, title in (("pd", "Public domain & open access"), ("still", "Copyrighted (fair use, commentary)")):
        rows.append(f"| **{title}** | | | |")
        for iid, c in sorted(credits.items()):
            if c["kind"] != kind or iid not in used:
                continue
            rows.append(f"| `{iid}` | {c['subject']} | {c['licence']} | [{'page' if c.get('page') else 'file'}]({c.get('page') or c.get('url')}) |")
    rows += ["", "**Not image files:** the Great Deku Tree is a paper-cut illustration drawn by the build script and labelled on screen; it doesn't reproduce Nintendo artwork.",
             "", "**Fair-use notes:** copyrighted images are low-resolution, appear only while the narration discusses them, are transformed into collage stickers, and are credited on the end card. No gameplay footage, film footage or official music is used."]
    src = (ROOT / "sources.md").read_text(encoding="utf-8")
    src = re.sub(r"## Images.*\Z", "\n".join(rows) + "\n", src, flags=re.S)
    (ROOT / "sources.md").write_text(src, encoding="utf-8")


if __name__ == "__main__":
    storyboard()
    images_section()
    print("wrote script/storyboard.md and the Images section of sources.md")
