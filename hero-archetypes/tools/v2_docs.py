"""Draft 2 docs: draft2/storyboard.md and draft2/collage_sources.md (credits for every collage image)."""
import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
D2 = ROOT / "draft2"


def mmss(t):
    return f"{int(t // 60)}:{t % 60:04.1f}"


def main():
    cfg = yaml.safe_load((D2 / "config.yaml").read_text())
    timing = json.loads((D2 / "build" / "timing.json").read_text())
    credits = json.loads((D2 / "collage_credits.json").read_text())
    excl = {l.split("#")[0].strip() for l in (D2 / "collage_exclude.txt").read_text().splitlines() if l.strip() and not l.startswith("#")}
    out = ["# Storyboard: The Hero With Infinite Faces (draft 2)", "",
           "Generated by `tools/v2_docs.py`. Vertical 9:16, text-led archival collage. "
           "Every spoken line appears on screen as serif text on paper strips; the collage builds continuously behind it.",
           f"Runtime: **{mmss(timing['duration'])}**", "",
           "| Time | Section (topic tag) | Hero images that land | Collage themes |", "|---|---|---|---|",
           f"| 0:00 | Title card: *{cfg['title']['line1']} {cfg['title']['line2']}* over Dürer, *Knight, Death and the Devil* | | |"]
    for s in timing["sections"]:
        heroes = cfg["heroes"].get(s["id"], [])
        themes = cfg["themes"].get(s["id"], [])
        out.append(f"| {mmss(s['start'])} | {s['id']}. {s['tag']} | {', '.join(heroes[:8])}{' …' if len(heroes) > 8 else ''} | {', '.join(themes)} |")
    out += ["", "## Lines and timings", ""]
    for s in timing["sections"]:
        out.append(f"### {s['id']}. {s['tag']}  ·  {mmss(s['start'])}")
        for ln in s["lines"]:
            out.append(f"- `{mmss(ln['start'])}` {ln['text']}")
        out.append("")
    (D2 / "storyboard.md").write_text("\n".join(out), encoding="utf-8")

    rows = ["# Collage image credits (draft 2)", "",
            "All images are public domain or openly licensed, harvested by `tools/harvest_esoteric.py`. "
            "Wellcome Collection images carry the Public Domain Mark or CC BY (credit: Wellcome Collection). "
            "Cleveland Museum of Art images are CC0. Art Institute of Chicago images are public domain.", "",
            "| Id | Title | Licence | Source |", "|---|---|---|---|"]
    for k, v in sorted(credits.items()):
        if k in excl:
            continue
        title = re.sub(r"\s+", " ", v.get("title", "")).replace("|", "/")[:110]
        rows.append(f"| `{k}` | {title} | {v['licence']} | [link]({v.get('page') or v['img']}) |")
    (D2 / "collage_sources.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print("wrote draft2/storyboard.md and draft2/collage_sources.md", len(rows) - 6, "images")


if __name__ == "__main__":
    main()
